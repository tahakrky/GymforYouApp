def ex(
    name, muscle, order, req, label, dumbbells, difficulty, video, sets, reps, rep_range, rest, desc, steps
) -> dict:
    primary = "dumbbell" if "dumbbell" in req else ("bodyweight" if "bodyweight" in req else req[0])
    lo, hi = _parse_range(rep_range, reps)
    act, secondary = ACTIVATION.get(name, (80, []))
    prog_to, prog_note = PROGRESSION.get(name, (None, None))
    return {
        "name": name,
        "muscle": muscle,
        "order": order,
        "equipment": primary,
        "equipment_required": req,
        "equipment_label": tr_label(label),
        "dumbbells_needed": dumbbells,
        "difficulty": difficulty,
        "video_id": video,
        "activation": act,
        "secondary": [{"muscle": m, "pct": p} for m, p in secondary],
        "target_sets": sets,
        "target_reps": reps,
        "rep_min": lo,
        "rep_max": hi,
        "rep_range": rep_range,
        "rest_sec": rest,
        "progression_to": prog_to,
        "progression_note": prog_note,
        "description": desc,
        "instructions": steps,
    }


def _parse_range(rep_range: str, reps: int) -> tuple[int, int]:
    """'8–12' / '10–14 per arm' / '30–60 sec' -> (8, 12). Falls back to reps ± 2."""
    import re as _re

    nums = _re.findall(r"\d+", rep_range or "")
    if len(nums) >= 2:
        lo, hi = int(nums[0]), int(nums[1])
        if lo <= hi:
            return lo, hi
    return max(1, reps - 2), reps + 2


