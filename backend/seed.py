async def main() -> None:
    # Library is curated data — replaced wholesale on every run. User data is never touched.
    await db.exercises.delete_many({})
    await db.exercises.insert_many([Exercise(**e).model_dump() for e in EXERCISES])

    baseline = Profile(
        weight_kg=76.5,
        weight_history=[{"date": today_iso(), "weight_kg": 76.5}],
    ).model_dump()
    await db.profiles.update_one({"id": "default"}, {"$setOnInsert": baseline}, upsert=True)

    # Existing profiles predate the equipment fields — backfill without clobbering user edits.
    await db.profiles.update_one(
        {"id": "default", "owned_equipment": {"$exists": False}},
        {"$set": {
            "owned_equipment": ["dumbbell", "bench", "bodyweight"],
            "dumbbell_weight_kg": 10.0,
            "dumbbell_count": 2,
            "equipment_filter_default": "mine",
            "plan_overrides": {},
        }},
    )

    await ensure_indexes()
    total = await db.exercises.count_documents({})
    home = await db.exercises.count_documents({"order": {"$lt": 50}})
    print(f"Seeded {total} exercises ({home} home-ready); profile upserted; indexes ensured.")

    client.close()


if __name__ == "__main__":
    asyncio.run(main())
